export function iconFor(game, stack) {
  if (!stack) return null;
  const key = stack.kind === 'block' ? `b${stack.id}` : stack.kind === 'tool' ? `t${stack.key}` : `s${stack.key}`;
  if (cache.has(key)) return cache.get(key);
  let url;
  if (stack.kind === 'block') url = blockIcon(game.atlas.tiles, BLOCKS[stack.id], 48);
  else if (stack.kind === 'tool') url = drawArt(document.createElement('canvas'), ART[stack.key] ?? ART.hand, 3).toDataURL();
  else {
    const def = SPAWNS[stack.key];
    const rows = SPAWN_ART[def?.category] ?? SPAWN_ART.Props;
    const c = document.createElement('canvas');
    c.width = c.height = 48;
    const g = c.getContext('2d');
    g.fillStyle = 'rgba(255,255,255,0.08)';
    g.beginPath(); g.arc(24, 24, 22, 0, Math.PI * 2); g.fill();
    rows.forEach((row, y) => { for (let x = 0; x < 16; x++) if (row[x] === '#') { g.fillStyle = def?.color ?? '#fff'; g.fillRect(x * 3, y * 3, 3, 3); } });
    g.strokeStyle = 'rgba(0,0,0,0.6)';
    g.lineWidth = 1;
    rows.forEach((row, y) => { for (let x = 0; x < 16; x++) if (row[x] === '#') g.strokeRect(x * 3 + 0.5, y * 3 + 0.5, 2, 2); });
    url = c.toDataURL();
  }
  cache.set(key, url);
  return url;
}
